import os, re, glob

def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')

def write(lang, idx):
    d = f"Localization/{lang}.lproj"
    os.makedirs(d, exist_ok=True)
    with open(f"{d}/Localizable.strings", "w", encoding="utf-8") as f:
        f.write(f"/* Kommandant – {lang}. Generated by Scripts/translations.py */\n\n")
        for k, v in T.items():
            value = k if idx is None else v[idx]
            f.write(f'"{esc(k)}" = "{esc(value)}";\n')
    with open(f"{d}/InfoPlist.strings", "w", encoding="utf-8") as f:
        f.write('"CFBundleDisplayName" = "Kommandant";\n')
        for k, v in INFO[lang].items():
            f.write(f'"{k}" = "{esc(v)}";\n')

def specs(s):
    return sorted(re.findall(r"%(?:\d+\$)?(?:ld|@|d)", s))

# Sanity checks: same format specifiers in every translation
for k, (en, it) in T.items():
    assert specs(k) == specs(en) == specs(it), (k, en, it)

write("de", None)
write("en", 0)
write("it", 1)
print(f"{len(T)} Texte → Localization/{{de,en,it}}.lproj")
